#!/bin/bash
# Compiles the shaders of the Vulkan backend to SPIR-V and writes them as C arrays to ../src/VulkanShaders.h.
# glslc is in the Android NDK: $ANDROID_NDK_HOME/shader-tools/<host>/glslc
set -e
cd "$(dirname "$0")"
GLSLC=${GLSLC:-glslc}
OUT=../src/VulkanShaders.h
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
{
    echo "// Generated by shaders/compile.sh from shaders/convert.vert and shaders/convert.frag: do not edit"
    echo "#pragma once"
    echo "#include <cstdint>"
    for stage in vert frag; do
        "$GLSLC" --target-env=vulkan1.1 -O -o "$TMP/convert.$stage.spv" convert.$stage
        echo "static const uint32_t kConvert_${stage}[] = {"
        od -An -v -tx4 "$TMP/convert.$stage.spv" | awk '{for (i = 1; i <= NF; i++) printf "0x%s,", $i; print ""}'
        echo "};"
    done
} > "$OUT"
echo "wrote $OUT"
